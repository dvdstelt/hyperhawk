import * as fs from 'fs';
import * as path from 'path';
import { parse as parseYaml } from 'yaml';

/**
 * The set of URL paths a Jekyll site generates at build time.
 *
 * Root-relative links in a Jekyll site usually point to generated pages
 * (e.g. /2024/01/15/my-post.html for _posts/2024-01-15-my-post.md) that
 * have no matching file on disk. This module computes those URLs from the
 * site sources so they can be verified without building the site.
 *
 * Supported: posts (global and front matter permalinks, categories),
 * pages, collections with output: true, redirect_from (jekyll-redirect-from)
 * and baseurl. Not supported: plugins that generate pages (pagination,
 * tag/category archives), data-driven pages, and Liquid in permalinks.
 */
export interface JekyllSite {
  /** Returns true if the root-relative URL path is generated by the site. */
  hasRoute(urlPath: string): boolean;
}

const MARKUP_EXTENSIONS = new Set(['.md', '.markdown', '.mkd', '.mkdn', '.mdown', '.html', '.htm']);
const POST_FILENAME = /^(\d{4})-(\d{2})-(\d{2})-(.+)$/;

// Built-in permalink styles: https://jekyllrb.com/docs/permalinks/#built-in-formats
const PERMALINK_STYLES: Record<string, string> = {
  date: '/:categories/:year/:month/:day/:title:output_ext',
  pretty: '/:categories/:year/:month/:day/:title/',
  ordinal: '/:categories/:year/:y_day/:title:output_ext',
  weekdate: '/:categories/:year/W:week/:short_day/:title:output_ext',
  none: '/:categories/:title:output_ext',
};

// Directories Jekyll never reads, plus the ones HyperHawk already skips.
const SKIPPED_DIRS = new Set(['node_modules', 'vendor', 'dist', 'lib']);

interface FrontMatter {
  [key: string]: unknown;
}

/**
 * Read the YAML front matter of a file. Returns undefined when the file
 * has no front matter block, and an empty object when it can't be parsed.
 */
function readFrontMatter(filePath: string): FrontMatter | undefined {
  let content: string;
  try {
    content = fs.readFileSync(filePath, 'utf8');
  } catch {
    return undefined;
  }
  const match = /^---\r?\n([\s\S]*?)\r?\n---\s*(\r?\n|$)/.exec(content);
  if (!match) return undefined;
  try {
    const data = parseYaml(match[1]);
    return data && typeof data === 'object' ? (data as FrontMatter) : {};
  } catch {
    return {};
  }
}

function toStringList(value: unknown): string[] {
  if (Array.isArray(value)) return value.map(v => String(v));
  if (typeof value === 'string') return value.split(/\s+/).filter(Boolean);
  return [];
}

/**
 * Normalize a URL path for lookups: collapse duplicate slashes and make
 * sure it starts with a slash.
 */
function normalize(urlPath: string): string {
  return ('/' + urlPath).replace(/\/{2,}/g, '/');
}

/**
 * Expand a permalink template. Unknown placeholders are left untouched.
 * Longer placeholder names are replaced first so :short_year doesn't
 * get mangled by :year.
 */
function expandPermalink(template: string, values: Record<string, string>): string {
  const keys = Object.keys(values).sort((a, b) => b.length - a.length);
  let url = template;
  for (const key of keys) {
    url = url.split(`:${key}`).join(values[key]);
  }
  return normalize(url);
}

function dayOfYear(year: number, month: number, day: number): string {
  const start = Date.UTC(year, 0, 1);
  const current = Date.UTC(year, month - 1, day);
  return String(Math.floor((current - start) / 86400000) + 1).padStart(3, '0');
}

function isoWeek(year: number, month: number, day: number): string {
  const date = new Date(Date.UTC(year, month - 1, day));
  const dayNum = date.getUTCDay() || 7;
  date.setUTCDate(date.getUTCDate() + 4 - dayNum);
  const yearStart = Date.UTC(date.getUTCFullYear(), 0, 1);
  return String(Math.ceil(((date.getTime() - yearStart) / 86400000 + 1) / 7)).padStart(2, '0');
}

function walk(dir: string, results: string[]): void {
  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIPPED_DIRS.has(entry.name)) continue;
      walk(fullPath, results);
    } else {
      results.push(fullPath);
    }
  }
}

function resolvePermalinkTemplate(permalink: unknown, fallback: string): string {
  if (typeof permalink !== 'string' || !permalink) return fallback;
  return PERMALINK_STYLES[permalink] ?? permalink;
}

/**
 * Compute the URL paths generated by the Jekyll site rooted at siteRoot.
 */
export function loadJekyllSite(siteRoot: string): JekyllSite {
  const routes = new Set<string>();
  const config = (readYamlFile(path.join(siteRoot, '_config.yml')) ?? {}) as FrontMatter;

  const baseurl = typeof config.baseurl === 'string' ? config.baseurl.replace(/\/+$/, '') : '';
  const globalPermalink = resolvePermalinkTemplate(config.permalink, PERMALINK_STYLES.date);
  const excluded = toStringList(config.exclude).map(e => e.replace(/^\/+|\/+$/g, ''));

  const collections = readCollections(config);
  const collectionsDir = typeof config.collections_dir === 'string' ? config.collections_dir : '';

  const addRoute = (url: string): void => {
    let p = normalize(url);
    if (p.endsWith('/')) p += 'index.html';
    routes.add(p);
  };

  const addRedirects = (fm: FrontMatter): void => {
    for (const r of toStringList(fm.redirect_from)) addRoute(r);
  };

  const allFiles: string[] = [];
  walk(siteRoot, allFiles);

  for (const file of allFiles) {
    const rel = path.relative(siteRoot, file).replace(/\\/g, '/');
    if (excluded.some(e => rel === e || rel.startsWith(e + '/'))) continue;

    const ext = path.extname(file).toLowerCase();
    if (!MARKUP_EXTENSIONS.has(ext)) continue;

    const segments = rel.split('/');
    const outputExt = '.html';

    // Posts: _posts/ at the root or under category folders (cat/_posts/).
    const postsIdx = segments.indexOf('_posts');
    const collectionRel = collectionsDir && rel.startsWith(collectionsDir + '/')
      ? rel.slice(collectionsDir.length + 1)
      : rel;
    const isUnderCollectionsDir = !collectionsDir || rel.startsWith(collectionsDir + '/');
    const collectionSegments = collectionRel.split('/');

    if (postsIdx >= 0 && isUnderCollectionsDir && segments.slice(0, postsIdx).every(s => !s.startsWith('_'))) {
      const base = path.basename(file, path.extname(file));
      const m = POST_FILENAME.exec(base);
      if (!m) continue;
      const fm = readFrontMatter(file) ?? {};
      if (fm.published === false) continue;

      const [, year, month, day, slug] = m;
      const folderCategories = segments.slice(collectionsDir ? collectionsDir.split('/').length : 0, postsIdx);
      const categories = [
        ...folderCategories,
        ...toStringList(fm.categories),
        ...toStringList(fm.category),
      ].map(c => c.toLowerCase());
      const uniqueCategories = [...new Set(categories)];
      const title = typeof fm.slug === 'string' ? fm.slug : slug;
      const y = parseInt(year, 10);
      const mo = parseInt(month, 10);
      const d = parseInt(day, 10);
      const values: Record<string, string> = {
        year,
        month,
        day,
        i_month: String(mo),
        i_day: String(d),
        short_year: year.slice(2),
        y_day: dayOfYear(y, mo, d),
        week: isoWeek(y, mo, d),
        short_day: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'][new Date(Date.UTC(y, mo - 1, d)).getUTCDay()],
        title,
        slug: title.toLowerCase(),
        name: slug,
        categories: uniqueCategories.join('/'),
        collection: 'posts',
        output_ext: outputExt,
      };
      const collectionPermalink = collections.get('posts')?.permalink;
      const template = resolvePermalinkTemplate(fm.permalink, resolvePermalinkTemplate(collectionPermalink, globalPermalink));
      addRoute(expandPermalink(template, values));
      addRedirects(fm);
      continue;
    }

    // Collections with output: true (_name/...).
    const first = collectionSegments[0];
    if (isUnderCollectionsDir && first.startsWith('_') && collectionSegments.length > 1) {
      const name = first.slice(1);
      const collection = collections.get(name);
      if (!collection || !collection.output || name === 'posts') continue;
      const fm = readFrontMatter(file) ?? {};
      if (fm.published === false) continue;

      const docPath = collectionSegments.slice(1).join('/');
      const pathWithoutExt = docPath.slice(0, docPath.length - path.extname(docPath).length);
      const basename = path.basename(pathWithoutExt);
      const values: Record<string, string> = {
        collection: name,
        path: pathWithoutExt,
        name: basename,
        title: typeof fm.slug === 'string' ? fm.slug : basename,
        slug: (typeof fm.slug === 'string' ? fm.slug : basename).toLowerCase(),
        output_ext: outputExt,
      };
      const template = resolvePermalinkTemplate(fm.permalink, collection.permalink ?? '/:collection/:path:output_ext');
      addRoute(expandPermalink(template, values));
      addRedirects(fm);
      continue;
    }

    // Anything else under an underscore folder (_layouts, _includes, _drafts, ...) isn't output.
    if (segments.some(s => s.startsWith('_'))) continue;

    // Pages.
    const fm = readFrontMatter(file);
    if (fm?.published === false) continue;
    if (fm && typeof fm.permalink === 'string' && fm.permalink) {
      addRoute(fm.permalink);
    } else {
      const withoutExt = rel.slice(0, rel.length - path.extname(rel).length);
      const isIndex = path.basename(withoutExt).toLowerCase() === 'index';
      const pretty = globalPermalink.endsWith('/');
      if (isIndex) {
        addRoute('/' + withoutExt + '.html');
      } else if (pretty) {
        addRoute('/' + withoutExt + '/');
      } else {
        addRoute('/' + withoutExt + '.html');
      }
    }
    if (fm) addRedirects(fm);
  }

  return {
    hasRoute(urlPath: string): boolean {
      let p = urlPath.split('?')[0];
      if (baseurl && (p === baseurl || p.startsWith(baseurl + '/'))) {
        p = p.slice(baseurl.length) || '/';
      }
      p = normalize(p);
      // Mirror how GitHub Pages serves files: /x, /x.html, and /x/ (index.html).
      const candidates = p.endsWith('/')
        ? [p + 'index.html']
        : [p, p + '.html', p + '/index.html'];
      return candidates.some(c => routes.has(c) || fs.existsSync(path.join(siteRoot, c)));
    },
  };
}

interface CollectionConfig {
  output: boolean;
  permalink?: string;
}

function readCollections(config: FrontMatter): Map<string, CollectionConfig> {
  const result = new Map<string, CollectionConfig>();
  const raw = config.collections;
  if (Array.isArray(raw)) {
    for (const name of raw) result.set(String(name), { output: false });
  } else if (raw && typeof raw === 'object') {
    for (const [name, value] of Object.entries(raw as Record<string, unknown>)) {
      const v = (value && typeof value === 'object' ? value : {}) as FrontMatter;
      result.set(name, {
        output: v.output === true,
        permalink: typeof v.permalink === 'string' ? v.permalink : undefined,
      });
    }
  }
  return result;
}

function readYamlFile(filePath: string): unknown {
  try {
    return parseYaml(fs.readFileSync(filePath, 'utf8'));
  } catch {
    return undefined;
  }
}
